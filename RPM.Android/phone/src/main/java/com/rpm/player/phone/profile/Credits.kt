package com.rpm.player.phone.profile

import android.content.Context
import androidx.annotation.StringRes
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.util.concurrent.ConcurrentHashMap

/**
 * One licence, as the iPhone's `CreditLicense`. [file] is the name of a file in the app's assets under `credits/`.
 * It is null when the licence is a published set of terms that only its publisher may host, and then the screen
 * can offer a link only.
 *
 * [isNotices] marks an aggregate notices document rather than one licence: it ships under [file], but the screen
 * sends the reader to [url], because the text is too long for one block. No entry on this head uses one yet; the
 * field is here so the table has the same shape on every head.
 */
class CreditLicense(val name: String, val file: String?, val url: String?, val isNotices: Boolean = false)

/**
 * One thing the Android phone ships or uses, as the iPhone's `CreditEntry`.
 *
 * [use] is a string resource that says what rpm uses it for. [source] is set only where a licence requires an
 * offer of the source, so it is not simply the project link. [termsUrl] is the address of the terms, for an entry
 * whose licence has no address of its own.
 */
class CreditEntry(
    val name: String,
    val version: String?,
    val detail: String?,
    val copyright: String?,
    val url: String?,
    val source: String?,
    @StringRes val use: Int?,
    val termsUrl: String?,
    val licenses: List<String>,
)

/** [note] is one sentence about the whole section, where the entries need a statement none of them could carry. */
class CreditSection(@StringRes val title: Int, @StringRes val note: Int?, val entries: List<CreditEntry>)

/**
 * The acknowledgements: what the Android phone ships that other people made, and what it uses.
 *
 * **The list is longer than the iPhone's, and this is correct.** The iPhone app is Swift on Apple's own frameworks
 * and carries no third-party code. This app is Kotlin on Jetpack Compose and Media3, loads pictures with Coil over
 * OkHttp, finds faces with ML Kit and carries an FFmpeg of its own for three formats Android cannot decode. Each is
 * named here, and nothing the phone does not carry is.
 *
 * The list itself is in `CreditsData.kt`, generated by `scripts/gen_credits.py` from `scripts/credits.json` in the
 * rpm repo, with the licence texts in `assets/credits`. This file holds what the generated table cannot: reading
 * those texts, and the rule for filling them in.
 */
object Credits {
    val licenses: Map<String, CreditLicense> get() = CreditsData.licenses
    val sections: List<CreditSection> get() = CreditsData.sections

    /** Licence texts already read, by file name. A few kilobytes each, and the same few are opened again and again. */
    private val read = ConcurrentHashMap<String, String>()

    /**
     * The text of a licence, with the holder's own copyright line filled in, read off the main thread. The iPhone
     * reads its file synchronously; here the read is moved to the IO pool because the main thread never waits on a
     * disk here, however small the file.
     *
     * A text that cannot be read gives the licence's address instead, as on iPhone, so the page is never empty.
     */
    suspend fun text(context: Context, licence: CreditLicense, copyright: String?): String {
        val file = licence.file ?: return ""
        val whole = read[file] ?: withContext(Dispatchers.IO) {
            runCatching { context.assets.open("credits/$file").bufferedReader().use { it.readText() } }.getOrNull()
        }?.also { read[file] = it } ?: return licence.url ?: ""
        return fill(whole, copyright)
    }

    /**
     * Puts [copyright] in place of the placeholder line, as the iPhone's `Credits.fill`. If there is no copyright,
     * the gap is closed instead.
     *
     * The texts are the licences as published. Permissive licences carry a placeholder line instead of a name, such
     * as MIT's `Copyright (c) <year> <copyright holders>`, and a licence that names nobody grants nothing. The
     * substitution is narrow: only a line that starts with `Copyright (c) <` is changed. The Open Font License has
     * no such line, and the Apache appendix's example uses square brackets, which are not a placeholder.
     *
     * Line ends are made `\n` first. The texts are committed with them, but a Windows checkout writes `\r\n`.
     */
    fun fill(text: String, copyright: String?): String {
        val lines = text.replace("\r\n", "\n").split("\n").toMutableList()
        val at = lines.indexOfFirst { it.startsWith("Copyright (c) <") }
        if (at < 0) return lines.joinToString("\n")

        if (!copyright.isNullOrEmpty()) {
            lines[at] = copyright
        } else {
            // Remove the line and the blank line under it, or the licence opens with two empty lines where a
            // name would be.
            val through = if (at + 1 < lines.size && lines[at + 1].isEmpty()) at + 1 else at
            for (i in through downTo at) lines.removeAt(i)
        }
        return lines.joinToString("\n")
    }
}
